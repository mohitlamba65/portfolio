export function buildHireMeMailto(email: string, name?: string) {
  const subject = encodeURIComponent("Hire me — Backend / AI engineering inquiry");
  const body = encodeURIComponent(
    `Hi ${name || "Mohit"},\n\nI'm reaching out about an opportunity.\n\n`
  );
  return `mailto:${email}?subject=${subject}&body=${body}`;
}
